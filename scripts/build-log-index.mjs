#!/usr/bin/env node

/**
 * scripts/build-log-index.mjs
 * 
 * Scans docs/worklog/*.md (excluding README.md), parses metadata,
 * sorts entries chronologically by timestamp, and generates /PROJECT_LOG.md.
 * 
 * Supports `--check` flag to verify that PROJECT_LOG.md is strictly up to date.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const worklogDir = path.join(rootDir, 'docs', 'worklog');
const projectLogPath = path.join(rootDir, 'PROJECT_LOG.md');

const isCheckMode = process.argv.includes('--check');

function parseWorklogFile(filePath, filename) {
  const content = fs.readFileSync(filePath, 'utf-8');
  
  const timestampMatch = content.match(/-\s+\*\*Timestamp\*\*:\s*`?([^`\r\n]+)`?/);
  const typeMatch = content.match(/-\s+\*\*Type\*\*:\s*`?([^`\r\n]+)`?/);
  const summaryMatch = content.match(/-\s+\*\*Summary\*\*:\s*([^\r\n]+)/);
  const authorMatch = content.match(/-\s+\*\*Author\*\*:\s*`?([^`\r\n]+)`?/);
  const directedByMatch = content.match(/-\s+\*\*Directed By\*\*:\s*`?([^`\r\n]+)`?/);
  const rationaleMatch = content.match(/-\s+\*\*Rationale\*\*:\s*([^\r\n]+)/);

  // Extract Files Touched list
  const filesTouched = [];
  const filesTouchedBlock = content.match(/-\s+\*\*Files Touched\*\*:\s*([\s\S]*?)(?=\n-\s+\*\*|\n#|\n---|$)/);
  if (filesTouchedBlock && filesTouchedBlock[1]) {
    const lines = filesTouchedBlock[1].split('\n');
    for (const line of lines) {
      const fileMatch = line.match(/^\s*-\s*`?([^`\r\n]+)`?/);
      if (fileMatch && fileMatch[1].trim()) {
        filesTouched.push(fileMatch[1].trim());
      }
    }
  }

  // Fallback timestamp from filename if not in content
  let timestamp = timestampMatch ? timestampMatch[1].trim() : '';
  if (!timestamp) {
    const nameMatch = filename.match(/^(\d{4}-\d{2}-\d{2}T\d{6}[+-]\d{4})/);
    if (nameMatch) {
      timestamp = nameMatch[1];
    }
  }

  return {
    filename,
    relativePath: `docs/worklog/${filename}`,
    timestamp,
    type: typeMatch ? typeMatch[1].trim() : 'docs',
    summary: summaryMatch ? summaryMatch[1].trim() : 'No summary provided',
    author: authorMatch ? authorMatch[1].trim() : 'unknown',
    directedBy: directedByMatch ? directedByMatch[1].trim() : 'unknown',
    rationale: rationaleMatch ? rationaleMatch[1].trim() : '',
    filesTouched,
  };
}

function buildProjectLog(entries) {
  // Sort ascending by timestamp
  entries.sort((a, b) => a.timestamp.localeCompare(b.timestamp));

  let md = `# Project Log\n\n`;
  md += `This file is an auto-generated index of all immutable worklog entries recorded in [\`docs/worklog/\`](./docs/worklog/).\n\n`;
  md += `> **DO NOT EDIT THIS FILE DIRECTLY.**\n`;
  md += `> This index is regenerated automatically via \`node scripts/build-log-index.mjs\`.\n\n`;
  md += `## Worklog Summary\n\n`;
  md += `| Timestamp | Type | Summary | Author | Directed By | Entry Link |\n`;
  md += `|---|:---:|---|:---:|:---:|---|\n`;

  for (const entry of entries) {
    const cleanSummary = entry.summary.replace(/\|/g, '\\|');
    md += `| \`${entry.timestamp}\` | \`${entry.type}\` | ${cleanSummary} | \`${entry.author}\` | \`${entry.directedBy}\` | [${entry.filename}](./${entry.relativePath}) |\n`;
  }

  md += `\n---\n\n`;
  md += `## Detailed Chronological History\n\n`;

  for (const entry of entries) {
    md += `### [${entry.timestamp}] ${entry.summary}\n`;
    md += `- **Type**: \`${entry.type}\`\n`;
    md += `- **Author**: \`${entry.author}\`\n`;
    md += `- **Directed By**: \`${entry.directedBy}\`\n`;
    md += `- **Worklog File**: [${entry.relativePath}](./${entry.relativePath})\n`;
    if (entry.rationale) {
      md += `- **Rationale**: ${entry.rationale}\n`;
    }
    if (entry.filesTouched.length > 0) {
      md += `- **Files Touched**:\n`;
      for (const f of entry.filesTouched) {
        md += `  - \`${f}\`\n`;
      }
    }
    md += `\n`;
  }

  return md;
}

function run() {
  if (!fs.existsSync(worklogDir)) {
    console.error(`Error: worklog directory does not exist at ${worklogDir}`);
    process.exit(1);
  }

  const files = fs.readdirSync(worklogDir).filter(
    (file) => file.endsWith('.md') && file.toLowerCase() !== 'readme.md'
  );

  const entries = files.map((file) =>
    parseWorklogFile(path.join(worklogDir, file), file)
  );

  const generatedLog = buildProjectLog(entries);

  if (isCheckMode) {
    if (!fs.existsSync(projectLogPath)) {
      console.error('Error: PROJECT_LOG.md does not exist. Run "node scripts/build-log-index.mjs" to create it.');
      process.exit(1);
    }
    const currentLog = fs.readFileSync(projectLogPath, 'utf-8');
    // Normalize line endings for cross-platform comparison
    const normCurrent = currentLog.replace(/\r\n/g, '\n').trim();
    const normGenerated = generatedLog.replace(/\r\n/g, '\n').trim();

    if (normCurrent !== normGenerated) {
      console.error('Error: PROJECT_LOG.md is out of date with docs/worklog/ entries.');
      console.error('Run "node scripts/build-log-index.mjs" to regenerate it and commit the changes.');
      process.exit(1);
    }

    console.log('Success: PROJECT_LOG.md is strictly up to date with docs/worklog/.');
    process.exit(0);
  }

  fs.writeFileSync(projectLogPath, generatedLog, 'utf-8');
  console.log(`Successfully generated PROJECT_LOG.md with ${entries.length} entries.`);
}

run();
